/**
 * Client-side AWS onboarding helpers.
 *
 * The backend (cloud-account-service) does not generate an external id: it
 * hashes the `external_account_id` supplied at create time and compares it at
 * verify time. So the external id is produced here, shown to the user, and
 * reused as `external_account_id` (create) and `external_id` (verify) so the
 * stored hash matches.
 *
 * The CloudFormation template is likewise rendered here until a backend
 * endpoint exists (the orchestrator route returns 501 today). It is a fixed,
 * reviewed template: a scoped IAM role whose trust policy requires the
 * external id, so no long-lived access keys are ever pasted into the browser.
 */

import type { CloudProviderId } from "./types";

const EXTERNAL_ID_PREFIX = "prv";

/** Thrown when the template is asked for with an empty external id. */
export class TemplateInputError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TemplateInputError";
  }
}

function randomHex(bytes: number): string {
  const array = new Uint8Array(bytes);
  if (typeof crypto !== "undefined" && typeof crypto.getRandomValues === "function") {
    crypto.getRandomValues(array);
  } else {
    for (let i = 0; i < array.length; i += 1) {
      array[i] = Math.floor(Math.random() * 256);
    }
  }
  return Array.from(array, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

/**
 * Generates an opaque external id of the form `prv_<provider>_<48 hex chars>`.
 * Only `[a-z0-9_]` so it is safe inside the CloudFormation trust policy.
 */
export function generateExternalId(provider: CloudProviderId = "aws"): string {
  return `${EXTERNAL_ID_PREFIX}_${provider}_${randomHex(24)}`;
}

export type CloudFormationTemplateInput = {
  externalId: string;
  workspaceId: string;
  accountLabel?: string;
  /**
   * The Provisr AWS account id the role is allowed to be assumed by. Left as a
   * placeholder until the platform publishes its role-assuming account id.
   */
  trustPrincipalAccountId?: string;
};

/**
 * Builds a deterministic CloudFormation template granting Provisr a scoped
 * execution role. The external id in the trust policy must match the value
 * entered on the connect panel; the same value is sent to the backend on
 * create and verify.
 */
export function buildCloudFormationTemplate(input: CloudFormationTemplateInput): string {
  const externalId = input.externalId.trim();
  if (externalId === "") {
    throw new TemplateInputError("An external id is required to render the template.");
  }
  const workspaceId = input.workspaceId.trim();
  if (workspaceId === "") {
    throw new TemplateInputError("A workspace id is required to render the template.");
  }

  const accountLabel = (input.accountLabel ?? "Provisr execution").trim() || "Provisr execution";
  const principalAccount =
    (input.trustPrincipalAccountId ?? "123456789012").trim() || "123456789012";

  return `AWSTemplateFormatVersion: "2010-09-09"
Description: >-
  Provisr delegated execution role for ${workspaceId}.
  Grants Provisr scoped access to provision resources in this account.
  RoleName: ProvisrExecutionRole (label: ${accountLabel}).

Parameters:
  ExternalId:
    Type: String
    Description: External id generated by Provisr. Must match the value shown in the connect panel.
    Default: ${externalId}

Resources:
  ProvisrExecutionRole:
    Type: AWS::IAM::Role
    Properties:
      RoleName: ProvisrExecutionRole
      Description: Scoped execution role assumed by Provisr for workspace ${workspaceId}.
      AssumeRolePolicyDocument:
        Version: "2012-10-17"
        Statement:
          - Effect: Allow
            Principal:
              AWS: arn:aws:iam::${principalAccount}:root
            Action: sts:AssumeRole
            Condition:
              StringEquals:
                sts:ExternalId: !Ref ExternalId
      Policies:
        - PolicyName: ProvisrProvisioning
          PolicyDocument:
            Version: "2012-10-17"
            Statement:
              - Effect: Allow
                Action:
                  - ec2:Describe*
                  - rds:Describe*
                  - s3:ListAllMyBuckets
                  - s3:GetBucketLocation
                  - sts:GetCallerIdentity
                Resource: "*"
              - Effect: Allow
                Action:
                  - iam:SimulatePrincipalPolicy
                Resource: "*"

Outputs:
  RoleArn:
    Description: Role ARN to paste back into Provisr to verify the connection.
    Value: !GetAtt ProvisrExecutionRole.Arn
`;
}

/**
 * Masks an AWS account id for display, keeping the last four digits:
 * `123456789012` -> `********9012`.
 */
export function maskAccountId(accountId: string | undefined | null): string {
  const value = (accountId ?? "").trim();
  if (value === "") {
    return "—";
  }
  if (value.length <= 4) {
    return "*".repeat(value.length);
  }
  return `${"*".repeat(value.length - 4)}${value.slice(-4)}`;
}
